"""Ports (interfaces) the application depends on. Infrastructure implements them."""

from __future__ import annotations

from contextlib import AbstractContextManager
from dataclasses import dataclass
from datetime import date, datetime
from typing import Any, Literal, Protocol

from ppos.domain.book import Book, BookNode, PromptVersion
from ppos.domain.career import EvidenceLink, Expectation
from ppos.domain.daily import DailyPlan
from ppos.domain.documents import Chunk, DocStatus, Document
from ppos.domain.facts import Fact, FactRun
from ppos.domain.meetings import Meeting, MeetingSeries, Person, Topic
from ppos.domain.notes import EntityType, Link, Note, NoteKind, NoteVersion
from ppos.domain.planning import ScopeEvent, Sprint, WeeklyPlan
from ppos.domain.projects import Project
from ppos.domain.tasks import Task, TaskStatus

Actor = Literal["user", "system", "ai"]


@dataclass(frozen=True)
class TaskQuery:
    statuses: tuple[TaskStatus, ...] = ()
    scheduled_date: date | None = None
    scheduled_before: date | None = None
    unscheduled_only: bool = False
    project_id: str | None = None
    parent_id: str | None = None
    top_level_only: bool = False
    tag: str | None = None
    sprint_id: str | None = None
    scheduled_from: date | None = None
    scheduled_to: date | None = None
    completed_from: datetime | None = None
    completed_to: datetime | None = None
    limit: int = 200
    offset: int = 0


@dataclass(frozen=True)
class NoteQuery:
    kind: NoteKind | None = None
    project_id: str | None = None
    note_date: date | None = None
    limit: int = 100
    offset: int = 0


@dataclass(frozen=True)
class SearchHit:
    entity_type: EntityType
    entity_id: str
    title: str
    snippet: str
    score: float


class TaskRepository(Protocol):
    def add(self, task: Task) -> None: ...
    def get(self, task_id: str) -> Task | None: ...
    def update(self, task: Task) -> None: ...
    def delete(self, task_id: str) -> None: ...
    def find(self, query: TaskQuery) -> list[Task]: ...
    def dependencies(self) -> dict[str, set[str]]: ...
    def dependencies_of(self, task_id: str) -> list[str]: ...
    def add_dependency(self, task_id: str, depends_on: str) -> None: ...
    def remove_dependency(self, task_id: str, depends_on: str) -> None: ...
    def max_position(self, status: TaskStatus, day: date | None) -> float: ...


class ProjectRepository(Protocol):
    def add(self, project: Project) -> None: ...
    def get(self, project_id: str) -> Project | None: ...
    def find_by_name(self, name: str) -> Project | None: ...
    def update(self, project: Project) -> None: ...
    def find(self, include_archived: bool = False) -> list[Project]: ...


class NoteRepository(Protocol):
    def add(self, note: Note) -> None: ...
    def get(self, note_id: str) -> Note | None: ...
    def update(self, note: Note) -> None: ...
    def delete(self, note_id: str) -> None: ...
    def find(self, query: NoteQuery) -> list[Note]: ...
