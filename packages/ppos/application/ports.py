class UnitOfWork(Protocol):
    """Transactional boundary; one per request/use case."""

    # Read-only properties so concrete UoWs may expose concrete repositories.
    @property
    def tasks(self) -> TaskRepository: ...
    @property
    def projects(self) -> ProjectRepository: ...
    @property
    def notes(self) -> NoteRepository: ...
    @property
    def days(self) -> DailyPlanRepository: ...
    @property
    def links(self) -> LinkRepository: ...
    @property
    def search(self) -> SearchIndex: ...
    @property
    def audit(self) -> AuditLog: ...
    @property
    def settings(self) -> SettingsRepository: ...
    @property
    def sprints(self) -> SprintRepository: ...
    @property
    def weeks(self) -> WeeklyPlanRepository: ...
    @property
    def people(self) -> PeopleRepository: ...
    @property
    def topics(self) -> TopicRepository: ...
    @property
    def meetings(self) -> MeetingRepository: ...
    @property
    def books(self) -> BookRepository: ...
    @property
    def documents(self) -> DocumentRepository: ...
    @property
    def facts(self) -> FactRepository: ...
    @property
    def career(self) -> CareerRepository: ...

    def commit(self) -> None: ...
    def rollback(self) -> None: ...


class UnitOfWorkFactory(Protocol):
    def __call__(self) -> AbstractContextManager[UnitOfWork]: ...
