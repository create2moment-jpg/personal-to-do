"""Ports (interfaces) the application depends on. Infrastructure implements them."""

from __future__ import annotations

from contextlib import AbstractContextManager
from dataclasses import dataclass
from datetime import date
from typing import Any, Literal, Protocol

from ppos.domain.daily import DailyPlan
from ppos.domain.notes import EntityType, Link, Note, NoteKind, NoteVersion
from ppos.domain.projects import Project
from ppos.domain.tasks import Task, TaskStatus

Actor = Literal["user", "system", "ai"]


@dataclass(frozen=True)
class TaskQuery:
    statuses: tuple[TaskStatus, ...] = ()
    scheduled_date: date | None = None
    scheduled_before: date | None = None
    unscheduled_only: bool = False
    project_id: str | None = None
    parent_id: str | None = None
    top_level_only: bool = False
    tag: str | None = None
    limit: int = 200
    offset: int = 0


@dataclass(frozen=True)
class NoteQuery:
    kind: NoteKind | None = None
    project_id: str | None = None
    note_date: date | None = None
    limit: int = 100
    offset: int = 0


@dataclass(frozen=True)
class SearchHit:
    entity_type: EntityType
    entity_id: str
    title: str
    snippet: str
    score: float


class TaskRepository(Protocol):
    def add(self, task: Task) -> None: ...
    def get(self, task_id: str) -> Task | None: ...
    def update(self, task: Task) -> None: ...
    def delete(self, task_id: str) -> None: ...
    def find(self, query: TaskQuery) -> list[Task]: ...
    def dependencies(self) -> dict[str, set[str]]: ...
    def dependencies_of(self, task_id: str) -> list[str]: ...
    def add_dependency(self, task_id: str, depends_on: str) -> None: ...
    def remove_dependency(self, task_id: str, depends_on: str) -> None: ...
    def max_position(self, status: TaskStatus, day: date | None) -> float: ...


class ProjectRepository(Protocol):
    def add(self, project: Project) -> None: ...
    def get(self, project_id: str) -> Project | None: ...
    def find_by_name(self, name: str) -> Project | None: ...
    def update(self, project: Project) -> None: ...
    def find(self, include_archived: bool = False) -> list[Project]: ...


class NoteRepository(Protocol):
    def add(self, note: Note) -> None: ...
    def get(self, note_id: str) -> Note | None: ...
    def update(self, note: Note) -> None: ...
    def delete(self, note_id: str) -> None: ...
    def find(self, query: NoteQuery) -> list[Note]: ...
    def add_version(self, version: NoteVersion) -> None: ...
    def versions(self, note_id: str) -> list[NoteVersion]: ...
    def get_version(self, note_id: str, version: int) -> NoteVersion | None: ...
    def find_daily_journal(self, day: date) -> Note | None: ...


class DailyPlanRepository(Protocol):
    def get(self, day: date) -> DailyPlan | None: ...
    def upsert(self, plan: DailyPlan) -> None: ...


class LinkRepository(Protocol):
    def add(self, link: Link) -> None: ...
    def delete(self, link_id: str) -> None: ...
    def for_entity(self, entity_type: EntityType, entity_id: str) -> list[Link]: ...
    def delete_for_entity(self, entity_type: EntityType, entity_id: str) -> None: ...


class SearchIndex(Protocol):
    def search(self, query: str, limit: int = 20) -> list[SearchHit]: ...


class AuditLog(Protocol):
    def record(
        self,
        entity_type: str,
        entity_id: str,
        action: str,
        actor: Actor = "user",
        details: dict[str, Any] | None = None,
    ) -> None: ...


class UnitOfWork(Protocol):
    """Transactional boundary; one per request/use case."""

    # Read-only properties so concrete UoWs may expose concrete repositories.
    @property
    def tasks(self) -> TaskRepository: ...
    @property
    def projects(self) -> ProjectRepository: ...
    @property
    def notes(self) -> NoteRepository: ...
    @property
    def days(self) -> DailyPlanRepository: ...
    @property
    def links(self) -> LinkRepository: ...
    @property
    def search(self) -> SearchIndex: ...
    @property
    def audit(self) -> AuditLog: ...

    def commit(self) -> None: ...
    def rollback(self) -> None: ...


class UnitOfWorkFactory(Protocol):
    def __call__(self) -> AbstractContextManager[UnitOfWork]: ...
